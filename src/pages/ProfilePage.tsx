import { useState } from "react";
import { QRCodeSVG } from "qrcode.react";
import { toast } from "sonner";
import { Download, LibraryBig } from "lucide-react";
import { downloadIdCard } from "@/api";
import { useAuth } from "@/auth/AuthContext";
import { useI18n } from "@/i18n";
import { FullPageLoader } from "@/auth/guards";
import { Container } from "@/components/Layout";
import { PageHeader, Panel } from "@/components/Page";
import { fmtDate } from "@/lib/time";
import { Button } from "@/components/ui/button";

export default function ProfilePage() {
  const { me, loading } = useAuth();
  const { t } = useI18n();
  const [downloading, setDownloading] = useState(false);

  if (loading || !me) return <FullPageLoader />;
  const scanUrl = `${window.location.origin}/scan/${me.uuid}`;

  const download = async () => {
    setDownloading(true);
    try {
      await downloadIdCard();
      toast.success(t("toast.downloaded"));
    } catch {
      toast.error(t("toast.cardFail"));
    } finally {
      setDownloading(false);
    }
  };

  const rows: [string, React.ReactNode][] = [
    [t("profile.fullname"), me.name],
    [t("profile.email"), <span dir="ltr">{me.email}</span>],
    [t("profile.id"), <span dir="ltr" className="font-mono text-[14px]">{me.studentOrStaffId}</span>],
    [t("profile.phone"), me.phoneNumber ? <span dir="ltr">{me.phoneNumber}</span> : "—"],
    [t("profile.address"), me.address || "—"],
    [t("profile.role"), t(`role.${me.role}`)],
    [t("profile.since"), fmtDate(me.membershipStartDate)],
    [t("profile.limit"), <span><span className="tabular">{me.activeLoans} / {me.maxBorrowLimit}</span> {t("profile.inuse")}</span>],
  ];

  return (
    <Container>
      <PageHeader title={t("profile.title")} />

      <div className="mt-8 grid gap-8 lg:grid-cols-[minmax(0,1fr)_24rem]">
        <Panel title={t("profile.details")} flush>
          <dl className="divide-y">
            {rows.map(([k, v]) => (
              <div key={k} className="grid gap-1 px-4 py-3 sm:grid-cols-[12rem_1fr] sm:gap-4">
                <dt className="text-sm text-muted-foreground">{k}</dt>
                <dd className="text-[15px] text-ink">{v}</dd>
              </div>
            ))}
          </dl>
        </Panel>

        <section aria-labelledby="card-h">
          <h2 id="card-h" className="text-[15px] font-semibold">{t("profile.card")}</h2>
          <p className="mt-1 text-sm text-muted-foreground">{t("profile.cardHelp")}</p>

          {/* on-screen card; the downloadable PDF is generated by the backend (or in-browser in the demo) */}
          <div className="mt-4 overflow-hidden rounded-lg border bg-white shadow-[0_2px_8px_rgb(16_24_20/0.08)]" aria-label={t("profile.card")}>
            <div className="flex items-center gap-2.5 bg-brand px-4 py-3 text-white">
              <LibraryBig className="size-5" aria-hidden />
              <div className="leading-tight">
                <p className="text-sm font-semibold">{t("brand.library")}</p>
                <p className="text-xs text-white/80">LibBorrow</p>
              </div>
              <span className="ms-auto rounded-full bg-white/15 px-2.5 py-0.5 text-xs font-medium">{t(`role.${me.role}`)}</span>
            </div>
            <div className="flex items-end justify-between gap-4 p-4">
              <div className="min-w-0">
                <p className="text-lg font-semibold leading-tight">{me.name}</p>
                <p dir="ltr" className="mt-1 font-mono text-sm text-ink/80">{me.studentOrStaffId}</p>
                <p className="mt-3 text-xs text-muted-foreground">{t("profile.since")} {fmtDate(me.membershipStartDate)}</p>
              </div>
              <div className="shrink-0 rounded border p-1.5">
                <QRCodeSVG value={scanUrl} size={76} level="M" fgColor="#121A16" />
              </div>
            </div>
            <div className="h-1.5 bg-danger" aria-hidden />
          </div>

          <Button onClick={download} disabled={downloading} variant="outline" className="mt-4 w-full">
            <Download className="size-4" aria-hidden />
            {downloading ? t("profile.generating") : t("profile.download")}
          </Button>
        </section>
      </div>
    </Container>
  );
}
