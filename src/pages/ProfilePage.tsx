import { useState } from "react";
import { QRCodeSVG } from "qrcode.react";
import { toast } from "sonner";
import { CreditCard, LibraryBig } from "lucide-react";
import { downloadIdCard } from "@/api";
import { useAuth } from "@/auth/AuthContext";
import { FullPageLoader } from "@/auth/guards";
import { Button } from "@/components/ui/button";

export default function ProfilePage() {
  const { me, loading } = useAuth();
  const [downloading, setDownloading] = useState(false);

  if (loading || !me) return <FullPageLoader />;
  const scanUrl = `${window.location.origin}/scan/${me.uuid}`;

  const download = async () => {
    setDownloading(true);
    try {
      await downloadIdCard();
      toast.success("ID card PDF downloaded (generated server-side).");
    } catch {
      toast.error("Could not download the ID card — is the backend running?");
    } finally {
      setDownloading(false);
    }
  };

  return (
    <div className="space-y-6">
      <div>
        <p className="font-mono text-[11px] uppercase tracking-[0.3em] text-burnt">Member area</p>
        <h1 className="mt-1 text-3xl font-bold tracking-tight">Profile</h1>
      </div>

      <div className="grid gap-6 lg:grid-cols-[1fr_400px]">
        <div className="rounded-md border border-border bg-white p-6">
          <h2 className="font-mono text-[11px] font-semibold uppercase tracking-[0.25em] text-burnt">
            Account details
          </h2>
          <dl className="mt-4 grid grid-cols-1 gap-x-8 gap-y-4 sm:grid-cols-2">
            {([
              ["Full name", me.name],
              ["Email", me.email],
              ["Student / staff ID", me.studentOrStaffId],
              ["Phone", me.phoneNumber || "—"],
              ["Address", me.address || "—"],
              ["Role", me.role.toLowerCase()],
              ["Member since", me.membershipStartDate],
              ["Borrow limit", `${me.activeLoans} / ${me.maxBorrowLimit} in use`],
            ] as [string, string][]).map(([k, v]) => (
              <div key={k}>
                <dt className="font-mono text-[10px] uppercase tracking-widest text-muted-foreground">{k}</dt>
                <dd className="mt-0.5 text-sm font-medium">{v}</dd>
              </div>
            ))}
          </dl>
        </div>

        {/* digital ID card preview — the downloadable PDF is generated by the Django backend */}
        <div className="space-y-3">
          <div className="relative aspect-[85.6/54] w-full overflow-hidden rounded-md bg-ink p-5 text-white shadow-lg" aria-label="Digital library ID card">
            <div className="absolute -right-8 -top-8 size-40 rounded-full bg-burnt/60" />
            <div className="absolute -bottom-10 -left-6 size-32 rounded-full bg-brand/40" />
            <div className="relative flex h-full flex-col justify-between">
              <div className="flex items-start justify-between">
                <div className="flex items-center gap-2">
                  <span className="flex size-7 items-center justify-center rounded-sm bg-burnt">
                    <LibraryBig className="size-4" />
                  </span>
                  <div className="leading-none">
                    <p className="text-sm font-bold">LibBorrow</p>
                    <p className="font-mono text-[8px] uppercase tracking-[0.25em] opacity-70">City Central Library</p>
                  </div>
                </div>
                <span className="rounded-sm bg-white/15 px-1.5 py-0.5 font-mono text-[9px] uppercase tracking-widest">{me.role}</span>
              </div>
              <div className="flex items-end justify-between gap-3">
                <div>
                  <p className="text-base font-bold leading-tight">{me.name}</p>
                  <p className="font-mono text-[10px] tracking-wider opacity-80">{me.studentOrStaffId}</p>
                  <p className="mt-1 font-mono text-[9px] uppercase tracking-widest opacity-60">
                    since {me.membershipStartDate} · loans {me.activeLoans}/{me.maxBorrowLimit}
                  </p>
                </div>
                <div className="rounded-sm bg-white p-1">
                  <QRCodeSVG value={scanUrl} size={56} level="M" />
                </div>
              </div>
            </div>
          </div>
          <Button onClick={download} disabled={downloading} className="w-full bg-brand text-white hover:bg-brand-dark">
            <CreditCard className="mr-1.5 size-4" />
            {downloading ? "Generating PDF…" : "Download my ID card (PDF)"}
          </Button>
          <p className="text-center font-mono text-[10px] text-muted-foreground">
            Server-side ReportLab PDF · QR encodes the staff scan-in URL
          </p>
        </div>
      </div>
    </div>
  );
}
