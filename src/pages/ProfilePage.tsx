import { useEffect, useState } from "react";
import { useLocation } from "react-router";
import { useMutation } from "@tanstack/react-query";
import { QRCodeSVG } from "qrcode.react";
import { toast } from "sonner";
import { Download } from "lucide-react";
import { apiAuth, downloadIdCard } from "@/api";
import { useAuth } from "@/auth/AuthContext";
import { useI18n } from "@/i18n";
import { FullPageLoader } from "@/auth/guards";
import { Container } from "@/components/Layout";
import { PageHeader, Panel } from "@/components/Page";
import { Wordmark } from "@/components/Wordmark";
import { errorMessage } from "@/lib/errors";
import { fmtDate } from "@/lib/time";
import { Button } from "@/components/ui/button";
import { Checkbox } from "@/components/ui/checkbox";
import { Label } from "@/components/ui/label";

export default function ProfilePage() {
  const { me, loading, refresh } = useAuth();
  const { t } = useI18n();
  const [downloading, setDownloading] = useState(false);
  const { hash } = useLocation();
  const ready = !loading && !!me;

  // Saves straight away: the box shows the value being saved until the profile reloads.
  const reminders = useMutation({
    mutationFn: apiAuth.setEmailReminders,
    onSuccess: async (profile) => {
      await refresh();
      toast.success(t(profile.emailReminders ? "toast.remindersOn" : "toast.remindersOff"));
    },
    onError: (e) => {
      toast.error(errorMessage(t, e));
    },
  });

  // "Show my card" on My loans links here: the card is not on the page until the profile has loaded.
  useEffect(() => {
    if (ready && hash === "#card") document.getElementById("card")?.scrollIntoView({ block: "start" });
  }, [ready, hash]);

  if (loading || !me) return <FullPageLoader />;
  const scanUrl = `${window.location.origin}/scan/${me.uuid}`;

  const download = async () => {
    setDownloading(true);
    try {
      await downloadIdCard();
      toast.success(t("toast.downloaded"));
    } catch {
      toast.error(t("toast.cardFail"));
    } finally {
      setDownloading(false);
    }
  };

  const rows: [string, React.ReactNode][] = [
    [t("profile.fullname"), me.name],
    [t("profile.email"), <span dir="ltr">{me.email}</span>],
    [t("profile.id"), <span dir="ltr" className="font-mono text-[14px]">{me.studentOrStaffId}</span>],
    [t("profile.phone"), me.phoneNumber ? <span dir="ltr">{me.phoneNumber}</span> : "—"],
    [t("profile.address"), me.address || "—"],
    [t("profile.role"), t(`role.${me.role}`)],
    [t("profile.since"), fmtDate(me.membershipStartDate)],
    ...(me.role === "MEMBER"
      ? [[t("profile.limit"), <span><span className="tabular">{me.activeLoans} / {me.maxBorrowLimit}</span> {t("profile.inuse")}</span>] as [string, React.ReactNode]]
      : []), // staff and admins cannot borrow, so a loan limit means nothing to them
  ];

  return (
    <Container>
      <PageHeader title={t("profile.title")} />

      <div className="mt-8 grid gap-8 lg:grid-cols-[minmax(0,1fr)_26rem] lg:gap-12">
        <div className="space-y-8">
          <Panel title={t("profile.details")} flush>
            <dl className="divide-y">
              {rows.map(([k, v]) => (
                <div key={k} className="grid gap-1 px-4 py-3 sm:grid-cols-[12rem_1fr] sm:gap-4">
                  <dt className="text-sm text-muted-foreground">{k}</dt>
                  <dd className="text-[15px] text-ink">{v}</dd>
                </div>
              ))}
            </dl>
          </Panel>

          {me.role === "MEMBER" && (
            <Panel>
              <div className="flex items-start gap-3">
                <Checkbox
                  id="email-reminders"
                  className="mt-1"
                  checked={reminders.isPending ? reminders.variables : me.emailReminders}
                  disabled={reminders.isPending}
                  onCheckedChange={(v) => reminders.mutate(v === true)}
                  aria-describedby="email-reminders-help"
                />
                <div className="min-w-0">
                  <Label htmlFor="email-reminders" className="text-[15px] font-medium">{t("profile.reminders")}</Label>
                  <p id="email-reminders-help" className="mt-0.5 text-sm text-muted-foreground">{t("profile.remindersHelp")}</p>
                </div>
              </div>
            </Panel>
          )}
        </div>

        <section id="card" aria-labelledby="card-h" className="order-first scroll-mt-24 lg:sticky lg:top-24 lg:order-none lg:self-start">
          <h2 id="card-h" className="text-[15px] font-semibold">{t("profile.card")}</h2>
          <p className="mt-1 text-sm text-muted-foreground">{t("profile.cardHelp")}</p>

          {/* on-screen card; the downloadable PDF is generated by the backend (or in-browser in the demo).
              A hairline green frame inside a second, fainter one: the object a student carries, in the library's own colours. */}
          <div className="mt-4 rounded-xl border border-brand bg-white p-1.5 shadow-[0_1px_2px_rgb(16_24_20/0.05),0_14px_30px_-18px_rgb(16_24_20/0.28)]" aria-label={t("profile.card")}>
            <div className="flex min-h-[14.5rem] flex-col rounded-[calc(var(--radius)+1px)] border border-brand/25 p-5 sm:p-6">
              <div className="flex items-start justify-between gap-4">
                <Wordmark size="card" />
                <span className="shrink-0 rounded-full border border-brand/30 px-2.5 py-0.5 text-xs font-medium text-brand-dark">
                  {t(`role.${me.role}`)}
                </span>
              </div>
              <div className="mt-auto flex items-end justify-between gap-5 pt-8">
                <div className="min-w-0">
                  <p dir="auto" className="line-clamp-2 break-words font-display text-[1.625rem] font-semibold leading-[1.15] tracking-[-0.012em] text-ink">{me.name}</p>
                  <p dir="ltr" className="mt-2 font-mono text-[13.5px] text-ink/80 rtl:text-end">{me.studentOrStaffId}</p>
                  <p className="mt-4 text-xs text-muted-foreground">{t("profile.since")} {fmtDate(me.membershipStartDate)}</p>
                </div>
                <QRCodeSVG value={scanUrl} size={88} level="M" fgColor="#121A16" className="shrink-0" />
              </div>
            </div>
          </div>

          <Button onClick={download} disabled={downloading} variant="outline" className="mt-4 w-full">
            <Download className="size-4" aria-hidden />
            {downloading ? t("profile.generating") : t("profile.download")}
          </Button>
        </section>
      </div>
    </Container>
  );
}
