const DICTS: Record<Lang, Dict> = { en, fr, ar };

interface I18nState {
  lang: Lang;
  setLang: (l: Lang) => void;
  /** Translate a key; `{name}` placeholders are filled from `vars`. */
  t: (key: string, vars?: Record<string, string | number>) => string;
  dir: "ltr" | "rtl";
}

const I18nContext = createContext<I18nState | null>(null);

function readLang(): Lang {
  try {
    const saved = localStorage.getItem("lb_lang");
    if (saved === "en" || saved === "fr" || saved === "ar") return saved;
  } catch { /* storage unavailable */ }
  return "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(readLang);
  const dir = lang === "ar" ? "rtl" : "ltr";

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
    try { localStorage.setItem("lb_lang", lang); } catch { /* storage unavailable */ }
  }, [lang, dir]);

  const t = (key: string, vars?: Record<string, string | number>) => {
    const text = DICTS[lang][key] ?? en[key] ?? key;
    return vars ? text.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : text;
  };

  return (
    <I18nContext.Provider value={{ lang, setLang, t, dir }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n(): I18nState {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
